import "server-only";

import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { resolveUploadsDir } from "@/db/path";
import { createId } from "@/lib/ids";
import type { StorageDriver, StoredFile } from "./driver";

/**
 * Stores uploads on local disk, under UPLOADS_DIR.
 *
 * Files are grouped per project and named by generated id, never by the name
 * the user supplied. That is what keeps a filename like "../../../etc/passwd"
 * from escaping the uploads directory: the original name is only ever data in
 * the database, not part of a path.
 */
export class LocalStorageDriver implements StorageDriver {
  private root(): string {
    return resolveUploadsDir();
  }

  private projectDir(projectId: string): string {
    // Ids are generated by this application and contain no separators, but the
    // basename call means a malformed one still cannot climb out.
    return path.join(this.root(), path.basename(projectId));
  }

  /** Resolves a key to a path, refusing anything that escapes the root. */
  private resolveKey(key: string): string {
    const full = path.resolve(this.root(), key);
    const root = path.resolve(this.root());
    if (full !== root && !full.startsWith(root + path.sep)) {
      throw new Error("Refusing to access a path outside the uploads directory");
    }
    return full;
  }

  async write(
    projectId: string,
    filename: string,
    data: Buffer,
  ): Promise<StoredFile> {
    const dir = this.projectDir(projectId);
    await mkdir(dir, { recursive: true });

    // Keep the extension for content sniffing and nicer downloads; discard the
    // rest of the supplied name.
    const extension = path.extname(filename).slice(0, 16);
    const key = path.join(path.basename(projectId), `${createId("f")}${extension}`);

    await writeFile(this.resolveKey(key), data);
    return { key, size: data.byteLength };
  }

  async read(key: string): Promise<Buffer> {
    return readFile(this.resolveKey(key));
  }

  async delete(key: string): Promise<void> {
    await rm(this.resolveKey(key), { force: true });
  }

  async deleteProject(projectId: string): Promise<void> {
    await rm(this.projectDir(projectId), { recursive: true, force: true });
  }
}
